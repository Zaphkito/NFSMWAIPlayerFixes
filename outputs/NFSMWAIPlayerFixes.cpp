static bool SetExtension(wchar_t* path, const wchar_t* extension) {
    int length=lstrlenW(path), dot=-1;
    for(int i=length-1;i>=0;--i) {
        if(path[i]==L'\\' || path[i]==L'/')break;
        if(path[i]==L'.'){dot=i;break;}
    }
    if(dot<0 || dot+lstrlenW(extension)>=MAX_PATH)return false;
    lstrcpyW(path+dot,extension);return true;
}
